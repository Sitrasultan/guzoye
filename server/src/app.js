import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import mongoose from 'mongoose';
import { env } from './config/env.js';
import catalogRoutes from './routes/catalogRoutes.js';
import { notFound,errorHandler } from './middleware/errors.js';
const app=express();
app.disable('x-powered-by');
app.set('query parser','simple');
app.use(helmet());
app.use(cors({origin:env.clientOrigin}));
app.use(express.json({limit:'16kb'}));
if(env.mode!=='test')app.use(morgan('dev'));
app.use('/api',rateLimit({windowMs:15*60*1000,limit:500,standardHeaders:'draft-7',legacyHeaders:false,message:{message:'Too many requests. Please try again later.'}}));
app.get('/api/health',(req,res)=>{const connected=mongoose.connection.readyState===1;res.status(connected?200:503).json({status:connected?'ok':'unavailable',database:connected?'connected':'disconnected'});});
app.use('/api',catalogRoutes);
app.use(notFound);
app.use(errorHandler);
export default app;
