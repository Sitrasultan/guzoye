import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import { requireAuth, requireRoles } from '../middleware/auth.js';
import { requireCsrf } from '../middleware/csrf.js';
import { validateId } from '../middleware/validate.js';
import { asyncHandler } from '../middleware/errors.js';
import * as controller from '../controllers/guideRequestController.js';
const router = Router();
const writeLimit = rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, message: { message: 'Too many guide-request changes. Try again later.' } });
router.get('/guide/requests', requireAuth, requireRoles('guide'), asyncHandler(controller.myRequests));
router.post('/guide/requests', writeLimit, requireAuth, requireRoles('guide'), requireCsrf, asyncHandler(controller.createRequest));
router.delete('/guide/requests/:id', writeLimit, requireAuth, requireRoles('guide'), requireCsrf, validateId, asyncHandler(controller.cancelRequest));
router.get('/admin/guide-requests', requireAuth, requireRoles('admin'), asyncHandler(controller.listRequests));
router.patch('/admin/guide-requests/:id/approve', writeLimit, requireAuth, requireRoles('admin'), requireCsrf, validateId, asyncHandler(controller.decideRequest));
router.patch('/admin/guide-requests/:id/reject', writeLimit, requireAuth, requireRoles('admin'), requireCsrf, validateId, asyncHandler(controller.decideRequest));
export default router;
