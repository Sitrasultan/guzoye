import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import { requireAuth, requireRoles, requireApprovedGuide } from '../middleware/auth.js';
import { requireCsrf } from '../middleware/csrf.js';
import { validateId } from '../middleware/validate.js';
import { asyncHandler } from '../middleware/errors.js';
import * as controller from '../controllers/guideManagementController.js';
const router = Router();
router.use(requireAuth, requireRoles('guide'));
router.use(rateLimit({ windowMs: 15 * 60 * 1000, limit: 80, skip: req => ['GET', 'HEAD', 'OPTIONS'].includes(req.method), message: { message: 'Too many guide changes. Try again later.' } }));
router.get('/profile', asyncHandler(controller.profile));
router.patch('/profile', requireCsrf, asyncHandler(controller.updateProfile));
router.get('/summary', requireApprovedGuide, asyncHandler(controller.summary));
router.get('/tours', requireApprovedGuide, asyncHandler(controller.ownTours));
router.get('/tours/:id', requireApprovedGuide, validateId, asyncHandler(controller.ownTour));
export default router;
