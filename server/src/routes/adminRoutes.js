import { Router } from 'express';
import rateLimit from 'express-rate-limit';
import { requireAuth, requireRoles } from '../middleware/auth.js';
import { requireCsrf } from '../middleware/csrf.js';
import { validateId } from '../middleware/validate.js';
import { asyncHandler } from '../middleware/errors.js';
import * as controller from '../controllers/adminController.js';
const router = Router();
router.use(requireAuth, requireRoles('admin'));
router.use(rateLimit({ windowMs: 15 * 60 * 1000, limit: 80, skip: req => ['GET', 'HEAD', 'OPTIONS'].includes(req.method), message: { message: 'Too many admin changes. Try again later.' } }));
router.get('/stats', asyncHandler(controller.stats));
router.get('/guides', asyncHandler(controller.listApplications));
router.patch('/guides/:id/approve', requireCsrf, validateId, asyncHandler(controller.approveGuide));
router.patch('/guides/:id/reject', requireCsrf, validateId, asyncHandler(controller.rejectGuide));
router.get('/tours', asyncHandler(controller.tours));
router.patch('/tours/:id/guide', requireCsrf, validateId, asyncHandler(controller.reassign));
router.patch('/tours/:id/archive', requireCsrf, validateId, asyncHandler(controller.archive));
router.get('/users', asyncHandler(controller.users));
router.patch('/users/:id/deactivate', requireCsrf, validateId, asyncHandler(controller.deactivate));
router.get('/audit', asyncHandler(controller.auditLog));
export default router;
